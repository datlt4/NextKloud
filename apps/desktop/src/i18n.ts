import { createSignal } from "solid-js";

export type Lang = "vi" | "en" | "ja" | "zh";
export const LANGS: { id: Lang; label: string }[] = [
  { id: "vi", label: "Tiếng Việt" },
  { id: "en", label: "English" },
  { id: "ja", label: "日本語" },
  { id: "zh", label: "中文" },
];
const LOCALE: Record<Lang, string> = { vi: "vi-VN", en: "en-US", ja: "ja-JP", zh: "zh-CN" };

function detect(): Lang {
  try {
    const s = localStorage.getItem("nk-lang");
    if (s === "vi" || s === "en" || s === "ja" || s === "zh") return s;
  } catch {
    /* bỏ qua */
  }
  const n = (navigator.language || "vi").toLowerCase();
  if (n.startsWith("zh")) return "zh";
  if (n.startsWith("ja")) return "ja";
  if (n.startsWith("en")) return "en";
  return "vi";
}

const [lang, setLangSig] = createSignal<Lang>(detect());
export { lang };
/** Đặt ngôn ngữ (chỉ signal + localStorage; đồng bộ server do background.setLang lo). */
export function applyLang(l: Lang) {
  setLangSig(l);
  try {
    localStorage.setItem("nk-lang", l);
  } catch {
    /* bỏ qua */
  }
  document.documentElement.lang = l;
}
applyLang(detect());

/** Chuỗi giao diện. Thiếu key ở ngôn ngữ đang chọn -> rớt về tiếng Việt, rồi tới key. */
export function t(key: string, vars?: Record<string, string | number>): string {
  const d = D[lang()] ?? D.vi;
  let s = d[key] ?? D.vi[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

